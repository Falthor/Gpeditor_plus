        Build-Index.ps1 -Kind Cis, see recommendedStateText). Shared across all of
        the entry's profiles (like title/info/valueType) - doesn't depend
        on the active profile, unlike Get-CisRecommendationValueForProfile.
        Feeds the "CIS States" column (Administrative Templates only).
    #>
    param($CisEntry)

    if ($null -eq $CisEntry) { return $null }
    return $CisEntry.recommendedStateText
}

